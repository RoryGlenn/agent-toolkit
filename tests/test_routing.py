"""Exercise routing package dependencies and additive upgrades with real old project state."""

from __future__ import annotations

import contextlib
import io
import json
import shutil
import tempfile
import unittest
from pathlib import Path

import install
import project_bootstrap as project

ROOT = Path(__file__).resolve().parents[1]


class RoutingInstallationTests(unittest.TestCase):
    """Keep shared routing portable without silently installing every specialist."""

    def setUp(self) -> None:
        """Create isolated homes and old project copies; never touch personal installations."""
        temporary = tempfile.TemporaryDirectory()
        self.addCleanup(temporary.cleanup)
        self.base = Path(temporary.name).resolve()
        self.app = self.base / "app"
        self.available = install.inventory(ROOT)
        output = contextlib.redirect_stdout(io.StringIO())
        output.__enter__()
        self.addCleanup(output.__exit__, None, None, None)

    def bootstrap(self, **kwargs: object) -> None:
        """Invoke the actual bootstrap with the current catalog."""
        project.bootstrap(ROOT, self.app, self.available, install.AGENTS, install.IGNORED, **kwargs)

    def legacy(self) -> None:
        """Copy the actual version-one output generated by the published old installer."""
        shutil.copytree(ROOT / "tests/fixtures/pre-routing-project", self.app)
        instructions = self.app / "AGENTS.md"
        instructions.write_bytes(b"Project-specific guidance.\n\n" + instructions.read_bytes())
        (self.app / "unrelated.txt").write_text("preserve")

    def snapshot(self) -> dict[str, bytes]:
        """Capture all regular project bytes for refusal and dry-run assertions."""
        return {
            path.relative_to(self.app).as_posix(): path.read_bytes()
            for path in self.app.rglob("*")
            if path.is_file()
        }

    def test_old_manifest_adds_only_required_dependency_with_explicit_update(self) -> None:
        """A real old project upgrades, relocates and repeats without selecting other domains."""
        self.legacy()
        before = self.snapshot()
        with self.assertRaisesRegex(project.BootstrapError, "--update"):
            self.bootstrap()
        self.assertEqual(self.snapshot(), before)
        self.bootstrap(update=True, dry_run=True)
        self.assertEqual(self.snapshot(), before)
        self.bootstrap(update=True)
        manifest = json.loads((self.app / project.MANIFEST).read_text())
        self.assertEqual(manifest["skills"], ["release-and-docs-skill", "task-routing-skill"])
        self.assertEqual(manifest["hosts"], ["codex", "copilot"])
        self.assertTrue((self.app / ".agents/skills/task-routing-skill/SKILL.md").is_file())
        self.assertFalse((self.app / ".agents/skills/ddia-skill").exists())
        self.assertFalse((self.app / ".github/agents").exists())
        self.assertTrue(
            (self.app / "AGENTS.md").read_text().startswith("Project-specific guidance.")
        )
        self.assertEqual((self.app / "unrelated.txt").read_text(), "preserve")
        moved = self.base / "relocated"
        self.app.rename(moved)
        self.app = moved
        before = self.snapshot()
        self.bootstrap()
        self.assertEqual(self.snapshot(), before)
        self.assertFalse(any(path.is_symlink() for path in self.app.rglob("*")))

    def test_upgrade_still_rejects_unrelated_selection_and_host_changes(self) -> None:
        """Dependency expansion cannot become an arbitrary reconfiguration bypass."""
        self.legacy()
        before = self.snapshot()
        for kwargs in (
            {"skills": ["release-and-docs-skill", "documentation-skill"]},
            {"skills": ["task-routing-skill"]},
            {"target": "codex"},
        ):
            with (
                self.subTest(kwargs=kwargs),
                self.assertRaisesRegex(project.BootstrapError, "Changing project skills or hosts"),
            ):
                self.bootstrap(update=True, **kwargs)
            self.assertEqual(self.snapshot(), before)

    def test_upgrade_refuses_edited_owned_file_and_unmanaged_dependency_collision(self) -> None:
        """The whole dependency upgrade is preflighted before any managed content changes."""
        self.legacy()
        owned = self.app / ".agents/skills/release-and-docs-skill/SKILL.md"
        original = owned.read_bytes()
        owned.write_bytes(original + b"\nLocal customization.\n")
        before = self.snapshot()
        with self.assertRaisesRegex(project.BootstrapError, "edited or removed"):
            self.bootstrap(update=True)
        self.assertEqual(self.snapshot(), before)
        owned.write_bytes(original)
        collision = self.app / ".agents/skills/task-routing-skill/SKILL.md"
        collision.parent.mkdir(parents=True)
        collision.write_text("Unmanaged user routing.")
        before = self.snapshot()
        with self.assertRaisesRegex(project.BootstrapError, "Unmanaged destination"):
            self.bootstrap(update=True)
        self.assertEqual(self.snapshot(), before)

    def test_existing_dependency_links_survive_selected_install_restore(self) -> None:
        """A second selection owns only its changes and retains independently installed routing."""
        for host in ("codex", "copilot"):
            with self.subTest(host=host):
                home = self.base / host
                routing_receipt = install.install(
                    ROOT, host, ["task-routing-skill"], home, home / ".codex"
                )
                receipt = install.install(
                    ROOT, host, ["documentation-skill"], home, home / ".codex"
                )
                assert receipt is not None and routing_receipt is not None
                area = home / (".agents/skills" if host == "codex" else ".copilot/skills")
                self.assertEqual(
                    {p.name for p in area.iterdir()}, {"documentation-skill", "task-routing-skill"}
                )
                install.restore(receipt)
                self.assertTrue((area / "task-routing-skill").is_symlink())
                self.assertFalse((area / "documentation-skill").exists())
                install.restore(routing_receipt)
                self.assertFalse((area / "task-routing-skill").exists())

    def test_selected_copilot_skills_include_dependencies_without_roles(self) -> None:
        """The retained Copilot target supplies portable skills without named-role adapters."""
        for skill, expected_skills in (
            (
                "ddia-review-skill",
                {"ddia-review-skill", "ddia-skill", "task-routing-skill"},
            ),
            (
                "software-design-skill",
                {"software-design-skill", "task-routing-skill"},
            ),
        ):
            with self.subTest(skill=skill):
                home = self.base / skill
                receipt = install.install(ROOT, "copilot", [skill], home, home / ".codex")
                assert receipt is not None
                self.assertEqual(
                    {p.name for p in (home / ".copilot/skills").iterdir()}, expected_skills
                )
                self.assertFalse((home / ".copilot/agents").exists())
                install.restore(receipt)
                self.assertFalse((home / ".copilot/agents").exists())

    def test_every_shipped_selection_has_routing_without_selecting_other_domains(self) -> None:
        """Each entrypoint's shared pointer resolves through its actual install plan."""
        for skill in self.available:
            with self.subTest(skill=skill):
                paths = install.locations(self.base / skill, self.base / skill / ".codex")
                plan = install.plan_install(ROOT, "codex", [skill], paths, backup_existing=False)
                installed = {entry.name for entry in plan if entry.area == "codex-skills"}
                expected = {skill, "task-routing-skill"}
                if skill.startswith("ddia-"):
                    expected.add("ddia-skill")
                self.assertEqual(installed, expected)

    def test_reverse_restore_refuses_shared_routing_removal_for_both_hosts(self) -> None:
        """Restoring the first receipt cannot break a later independently installed skill."""
        for host in ("codex", "copilot"):
            with self.subTest(host=host):
                home = self.base / host
                first = install.install(ROOT, host, ["documentation-skill"], home, home / ".codex")
                second = install.install(
                    ROOT, host, ["software-design-skill"], home, home / ".codex"
                )
                assert first is not None and second is not None
                area = home / (".agents/skills" if host == "codex" else ".copilot/skills")
                before = {p.name: p.readlink() for p in area.iterdir()}
                receipt_before = first.read_bytes()
                for dry_run in (True, False):
                    with self.assertRaisesRegex(install.InstallError, "shared dependencies"):
                        install.restore(first, dry_run=dry_run)
                    self.assertEqual({p.name: p.readlink() for p in area.iterdir()}, before)
                    self.assertEqual(first.read_bytes(), receipt_before)
                install.restore(second)
                install.restore(first)
                self.assertEqual(list(area.iterdir()), [])

    def test_reverse_restore_protects_ddia_package_and_roles_with_existing_routing(self) -> None:
        """The guard applies to existing transitive DDIA resources, not only new routing."""
        for host in ("codex", "copilot"):
            with self.subTest(host=host):
                home = self.base / host
                routing = install.install(ROOT, host, ["task-routing-skill"], home, home / ".codex")
                shared = install.install(ROOT, host, ["ddia-skill"], home, home / ".codex")
                workflow = install.install(ROOT, host, ["ddia-review-skill"], home, home / ".codex")
                assert routing is not None and shared is not None and workflow is not None
                with self.assertRaisesRegex(install.InstallError, "shared dependencies"):
                    install.restore(shared)
                install.restore(workflow)
                install.restore(shared)
                install.restore(routing)

    def test_reverse_restore_protects_shared_engineering_roles(self) -> None:
        """A surviving workflow retains shared roles even when routing was installed earlier."""
        home = self.base / "home"
        routing = install.install(ROOT, "codex", ["task-routing-skill"], home, home / ".codex")
        review = install.install(
            ROOT, "codex", ["independent-diff-review-skill"], home, home / ".codex"
        )
        delivery = install.install(
            ROOT, "codex", ["issue-to-tested-pr-skill"], home, home / ".codex"
        )
        assert routing is not None and review is not None and delivery is not None
        with self.assertRaisesRegex(install.InstallError, "shared dependencies"):
            install.restore(review)
        self.assertEqual(len(list((home / ".codex/agents").iterdir())), 3)
        install.restore(delivery)
        install.restore(review)
        install.restore(routing)

    def test_skill_only_restore_still_cleans_dangling_links_without_source(self) -> None:
        """Dependency protection must not require opening a source tree that disappeared."""
        source = self.base / "source"
        for name in ("skills", "agents"):
            shutil.copytree(
                ROOT / name, source / name, ignore=shutil.ignore_patterns("__pycache__")
            )
        for host in ("codex", "copilot"):
            home = self.base / host
            receipt = install.install(
                source, host, ["release-and-docs-skill"], home, home / ".codex"
            )
            assert receipt is not None
            moved = self.base / "moved source"
            source.rename(moved)
            install.restore(receipt)
            area = home / (".agents/skills" if host == "codex" else ".copilot/skills")
            self.assertEqual(list(area.iterdir()), [])
            moved.rename(source)

    def test_restore_preserves_foreign_pre_routing_installation_for_both_hosts(self) -> None:
        """Replay actual old receipts; canonical names alone do not establish dependencies."""
        fixture = ROOT / "tests/fixtures/pre-routing-software"
        old_source = self.base / "old source"
        shutil.copytree(fixture, old_source)
        self.assertNotIn(
            "task-routing-skill", (old_source / "skills/software-design-skill/SKILL.md").read_text()
        )
        for host in ("codex", "copilot"):
            with self.subTest(host=host):
                home = self.base / host
                data = json.loads(
                    (fixture / "receipts.json")
                    .read_text()
                    .replace("__HOME__", str(home))
                    .replace("__SOURCE__", str(old_source))
                )[host]
                paths = install.locations(home, home / ".codex")
                old_paths = []
                for entry in data["entries"]:
                    destination = paths[entry["area"]] / entry["name"]
                    destination.parent.mkdir(parents=True, exist_ok=True)
                    if entry["area"] == "codex-agents":
                        destination.hardlink_to(entry["source"])
                    else:
                        destination.symlink_to(entry["source"], target_is_directory=True)
                    old_paths.append(destination)
                old_receipt = home / ".local/state/agent-toolkit/installations/old/receipt.json"
                old_receipt.parent.mkdir(parents=True)
                old_receipt.write_text(json.dumps(data, indent=2) + "\n")
                old_bytes = old_receipt.read_bytes()
                old_entries = {
                    p: (p.readlink() if p.is_symlink() else (p.stat().st_ino, p.read_bytes()))
                    for p in old_paths
                }
                current = install.install(
                    ROOT, host, ["documentation-skill"], home, home / ".codex"
                )
                assert current is not None
                install.restore(current, dry_run=True)
                install.restore(current)
                self.assertEqual(old_receipt.read_bytes(), old_bytes)
                self.assertEqual(
                    {
                        p: (p.readlink() if p.is_symlink() else (p.stat().st_ino, p.read_bytes()))
                        for p in old_paths
                    },
                    old_entries,
                )
                self.assertFalse(install.present(paths[f"{host}-skills"] / "task-routing-skill"))
                self.assertFalse(install.present(paths[f"{host}-skills"] / "documentation-skill"))
                install.restore(old_receipt)

    def test_old_project_update_retires_only_unchanged_owned_copilot_role(self) -> None:
        """The skill-only transition uses existing ownership checks, never broad deletion."""
        fixture = json.loads((ROOT / "tests/fixtures/pre-routing-copilot-project.json").read_text())
        for relative, state in fixture["files"].items():
            path = self.app / relative
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(state["text"])
            path.chmod(state["mode"])
        role = self.app / ".github/agents/documentation-agent.agent.md"
        original = role.read_bytes()
        unrelated = self.app / ".github/agents/team-owned-agent.agent.md"
        unrelated.write_text("Preserve this project-owned role.")
        role.write_bytes(original + b"\nLocal role customization.\n")
        before = self.snapshot()
        with self.assertRaisesRegex(project.BootstrapError, "edited or removed"):
            self.bootstrap(update=True)
        self.assertEqual(self.snapshot(), before)
        role.write_bytes(original)
        before = self.snapshot()
        self.bootstrap(update=True, dry_run=True)
        self.assertEqual(self.snapshot(), before)
        self.bootstrap(update=True)
        self.assertFalse(role.exists())
        self.assertEqual(unrelated.read_text(), "Preserve this project-owned role.")
        manifest = json.loads((self.app / project.MANIFEST).read_text())
        self.assertEqual(manifest["hosts"], ["copilot"])
        self.assertEqual(manifest["skills"], ["documentation-skill", "task-routing-skill"])
        self.assertNotIn(".github/agents/documentation-agent.agent.md", manifest["files"])
        self.assertFalse((self.app / ".codex/agents").exists())
        before = self.snapshot()
        self.bootstrap()
        self.assertEqual(self.snapshot(), before)

    def test_missing_routing_dependency_fails_before_project_creation(self) -> None:
        """A partial source checkout cannot silently create dangling runtime pointers."""
        del self.available["task-routing-skill"]
        with self.assertRaisesRegex(project.BootstrapError, "missing required skill"):
            self.bootstrap(skills=["documentation-skill"])
        self.assertFalse(self.app.exists())


if __name__ == "__main__":
    unittest.main()
